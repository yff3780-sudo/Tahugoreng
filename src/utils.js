// Format Rupiah standar: Rp 1.250.000
export function formatRupiah(angka) {
  if (angka === null || angka === undefined || isNaN(angka)) {
    return 'Rp 0';
  }
  const nilai = Math.round(Number(angka));
  const isNegatif = nilai < 0;
  const absNilai = Math.abs(nilai);
  const formatted = absNilai.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return `${isNegatif ? '-' : ''}Rp ${formatted}`;
}

// Format Rupiah ringkas untuk visualisasi grafik & badge (misal: 1,2 jt, 850 rb)
export function formatCompactRupiah(angka) {
  if (angka === null || angka === undefined || isNaN(angka)) return '0';
  const val = Math.abs(Number(angka));
  const tanda = Number(angka) < 0 ? '-' : '';

  if (val >= 1000000000) {
    return `${tanda}${(val / 1000000000).toFixed(1).replace('.0', '').replace('.', ',')} M`;
  }
  if (val >= 1000000) {
    return `${tanda}${(val / 1000000).toFixed(1).replace('.0', '').replace('.', ',')} jt`;
  }
  if (val >= 1000) {
    return `${tanda}${(val / 1000).toFixed(0)} rb`;
  }
  return `${tanda}${val}`;
}

// Format input angka nominal dengan pemisah ribuan saat diketik
export function formatNominalInput(inputStr) {
  if (!inputStr) return '';
  const clean = inputStr.toString().replace(/\D/g, '');
  if (!clean) return '';
  return clean.replace(/\B(?=(\d{3})+(?!\d))/g, '.');
}

// Mengurai string berformat atau teks bebas menjadi angka murni
export function parseNominal(str) {
  if (!str) return 0;
  if (typeof str === 'number') return str;
  const clean = str.toString().replace(/[^\d]/g, '');
  return clean ? parseInt(clean, 10) : 0;
}

// Nama hari dan bulan dalam Bahasa Indonesia
export const NAMA_HARI = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
export const NAMA_BULAN = [
  'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
  'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'
];
export const NAMA_BULAN_PENDEK = [
  'Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun',
  'Jul', 'Ags', 'Sep', 'Okt', 'Nov', 'Des'
];

// Format tanggal lengkap: "Kamis, 15 Oktober 2026"
export function formatTanggalLengkap(dateOrStr) {
  const d = new Date(dateOrStr);
  if (isNaN(d.getTime())) return '-';
  return `${NAMA_HARI[d.getDay()]}, ${d.getDate()} ${NAMA_BULAN[d.getMonth()]} ${d.getFullYear()}`;
}

// Format tanggal ringkas: "15 Okt 2026"
export function formatTanggal(dateOrStr) {
  const d = new Date(dateOrStr);
  if (isNaN(d.getTime())) return '-';
  return `${d.getDate()} ${NAMA_BULAN_PENDEK[d.getMonth()]} ${d.getFullYear()}`;
}

// Format jam: "14:30"
export function formatJam(dateOrStr) {
  const d = new Date(dateOrStr);
  if (isNaN(d.getTime())) return '';
  const jam = String(d.getHours()).padStart(2, '0');
  const menit = String(d.getMinutes()).padStart(2, '0');
  return `${jam}:${menit}`;
}

// Format input datetime-local HTML: YYYY-MM-DDTHH:mm
export function toDatetimeLocal(dateOrStr = new Date()) {
  const d = new Date(dateOrStr);
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

// String kunci bulan: "2026-10"
export function getBulanKey(date = new Date()) {
  const d = new Date(date);
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}`;
}

// Keamanan: Hash PIN 4-6 digit menggunakan SHA-256 Web Crypto API
export async function hashPIN(pin) {
  const encoder = new TextEncoder();
  const data = encoder.encode(`dompetku_salt_${pin}`);
  const hashBuffer = await crypto.subtle.digest('SHA-256', data);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

// Escape HTML untuk mencegah XSS
export function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

// Toast Notifikasi dengan opsi tombol 'Batalkan' (Undo) selama 5 detik
let toastTimeoutId = null;
export function showToast(pesan, tipe = 'info', onUndo = null, durasi = 4000) {
  const container = document.getElementById('toast-container');
  if (!container) return;

  if (toastTimeoutId) {
    clearTimeout(toastTimeoutId);
  }

  const toast = document.createElement('div');
  toast.className = `toast-item toast-${tipe} animate-fade-in`;

  let undoButtonHtml = '';
  if (onUndo && typeof onUndo === 'function') {
    undoButtonHtml = `<button class="btn-toast-undo" id="btn-toast-undo">Batalkan</button>`;
  }

  toast.innerHTML = `
    <div class="toast-content">
      <span class="toast-message">${escapeHtml(pesan)}</span>
      ${undoButtonHtml}
    </div>
  `;

  container.innerHTML = '';
  container.appendChild(toast);

  if (onUndo && typeof onUndo === 'function') {
    const btnUndo = toast.querySelector('#btn-toast-undo');
    if (btnUndo) {
      btnUndo.addEventListener('click', () => {
        onUndo();
        toast.remove();
        if (toastTimeoutId) clearTimeout(toastTimeoutId);
      });
    }
  }

  toastTimeoutId = setTimeout(() => {
    toast.classList.add('fade-out');
    setTimeout(() => toast.remove(), 300);
  }, durasi);
}

